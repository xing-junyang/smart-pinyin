    // MARK: - Segmentation

    /// Segment a raw pinyin string (e.g. "zhongguo") into syllables
    /// using greedy longest-match.
    static func segment(_ raw: String) -> [String] {
        let lower = raw.lowercased()
        var result: [String] = []
        var i = lower.startIndex

        while i < lower.endIndex {
            var bestLen = 0
            // Try up to 6 characters (longest pinyin: "zhuang", "chuang")
            let maxLen = min(6, lower.distance(from: i, to: lower.endIndex))
            for len in stride(from: maxLen, through: 1, by: -1) {
                let end = lower.index(i, offsetBy: len)
                let candidate = String(lower[i ..< end])
                if syllables.contains(candidate) {
                    bestLen = len
                    break
                }
            }

            if bestLen > 0 {
                let end = lower.index(i, offsetBy: bestLen)
                result.append(String(lower[i ..< end]))
                i = end
            } else {
                // Unknown segment — treat single char as-is
                result.append(String(lower[i]))
                i = lower.index(after: i)
            }
        }
        return result
    }

    /// Return all possible segmentations (DP-based).
    /// For ambiguous inputs like "xian" (xi+an vs xian).
    static func segmentAll(_ raw: String) -> [[String]] {
        let lower = raw.lowercased()
        let n = lower.count
        guard n > 0 else { return [[]] }

        // dp[i] = list of segmentations for suffix starting at i
        var dp: [[[String]]] = Array(repeating: [], count: n + 1)
        dp[n] = [[]]

        let chars = Array(lower)
        for i in stride(from: n - 1, through: 0, by: -1) {
            let maxLen = min(6, n - i)
            for len in 1 ... maxLen {
                let seg = String(chars[i ..< i + len])
                if syllables.contains(seg) {
                    for suffix in dp[i + len] {
                        dp[i].append([seg] + suffix)
                    }
                }
            }
        }
        return dp[0]
    }

    // MARK: - Candidate Lookup

    /// Get Chinese character candidates for a single pinyin syllable.
    static func candidates(for pinyin: String) -> [PinyinCandidate] {
        let lower = pinyin.lowercased()
        guard let chars = dict[lower] else { return [] }
        return chars.map { PinyinCandidate(character: $0, pinyin: lower) }
    }

    /// Get candidates for a multi-syllable pinyin input.
    /// Returns candidates syllable by syllable, plus common multi-character words.
    static func multiSyllableCandidates(for raw: String) -> [[PinyinCandidate]] {
        let segs = segment(raw)
        return segs.map { candidates(for: $0) }
    }
